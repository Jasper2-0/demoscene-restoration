import { Mat4 } from '../shared/mathlib.js';

const TRIANGLES_PER_HALF = 150;
const RAND_MAX = 32767;
const COLORED_PASS_RGB = Object.freeze([
  Math.fround(0.7411764860153198),
  Math.fround(0.3137255012989044),
  Math.fround(0.11372549086809158),
]);
const BLACK_PASS_ALPHA = Math.fround(0.5099999904632568);

class MsvcRand {
  constructor(seed = 1) { this.state = seed | 0; }

  next() {
    this.state = (Math.imul(this.state, 214013) + 2531011) | 0;
    return (this.state >> 16) & RAND_MAX;
  }

  unit() { return Math.fround(this.next() * Math.fround(1 / RAND_MAX)); }
}

function subtract(a, b) {
  return [Math.fround(a[0] - b[0]), Math.fround(a[1] - b[1]), Math.fround(a[2] - b[2])];
}

function cross(a, b) {
  return [
    a[1] * b[2] - a[2] * b[1],
    a[2] * b[0] - a[0] * b[2],
    a[0] * b[1] - a[1] * b[0],
  ];
}

function normalized(value) {
  const scale = 1 / (Math.hypot(...value) || 1);
  return value.map((component) => Math.fround(component * scale));
}

function dot(a, b) { return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]; }

/** Exact camera-basis convention used by Energia's matrix helper at 0x401050. */
export function energiaMainEffectViewMatrix(eye, target, roll) {
  const backward = normalized(subtract(eye, target));
  const seedUp = [Math.fround(Math.sin(roll)), Math.fround(Math.cos(roll)), 0];
  const right = normalized(cross(seedUp, backward));
  const up = normalized(cross(backward, right));
  const matrix = new Mat4();
  matrix.m.set([
    right[0], up[0], backward[0], 0,
    right[1], up[1], backward[1], 0,
    right[2], up[2], backward[2], 0,
    Math.fround(-dot(right, eye)),
    Math.fround(-dot(up, eye)),
    Math.fround(-dot(backward, eye)),
    1,
  ]);
  return matrix;
}

export function energiaMainEffectCamera(seconds) {
  const time = Math.fround(seconds);
  const phase = Math.fround(time * 0.12);
  const eye = [
    Math.fround(Math.sin(phase) * 180),
    0,
    Math.fround(Math.sin(phase * 0.58) * 100 - 360),
  ];
  const target = [0, -30, 0];
  return {
    phase,
    eye,
    target,
    viewMatrix: energiaMainEffectViewMatrix(eye, target, phase),
    translation: [0, -100, 0],
    rotation: [Math.fround(phase * 30), 1, 0, 0],
  };
}

export function energiaMainEffectFade(seconds) {
  const time = Math.fround(seconds);
  let alpha = Math.fround((time - 56) * 0.15);
  alpha = Math.max(0, Math.min(1, alpha));
  if (time > 157 && time < 194.5) alpha = Math.fround(alpha * 0.21);
  return alpha;
}

function buildHalf(seconds, direction, origin, endpoint) {
  const random = new MsvcRand(1);
  const delta = subtract(endpoint, origin);
  const vertices = [];
  for (let index = 0; index < TRIANGLES_PER_HALF; index++) {
    const length = Math.fround(Math.sin(index * 0.04 + seconds) * 400 + 100);
    const base = [
      Math.fround(delta[0] * random.unit() + origin[0]),
      Math.fround(delta[1] * (random.unit() - 0.5) + origin[1]),
      Math.fround(delta[2] * random.unit() + origin[2]),
    ];
    const noise = Math.sin(seconds * 4 + index * 0.2) * 500;
    const first = [
      Math.fround(noise * direction[0] + base[0]),
      Math.fround(noise * direction[1] + base[1]),
      Math.fround(noise * direction[2] + base[2]),
    ];
    const second = [
      Math.fround(length * direction[0] + base[0]),
      Math.fround(length * direction[1] + base[1]),
      Math.fround(length * direction[2] + base[2]),
    ];
    const jitter = (Math.sin(seconds * 0.3) * 15 + 40) * (random.unit() - 0.5);
    const third = [
      second[0],
      Math.fround(second[1] + jitter * direction[2]),
      Math.fround(second[2] + jitter * direction[1] * 2.4),
    ];
    vertices.push(first, second, third);
  }
  return vertices;
}

/** The two deterministic 150-triangle fans generated by 0x410cf0. */
export function buildEnergiaMainEffectTriangles(seconds) {
  const time = Math.fround(seconds);
  return [
    ...buildHalf(time, [0, 0, 1], [-300, -360, 0], [0, 0, 0]),
    ...buildHalf(time, [0, 0, 1], [0, 0, 0], [300, 360, 0]),
  ];
}

export function energiaMainEffectPasses(seconds) {
  const alpha = energiaMainEffectFade(seconds);
  const random = new MsvcRand(1);
  return Array.from({ length: 6 }, () => random.next() < 0x7ff
    ? [...COLORED_PASS_RGB, alpha]
    : [0, 0, 0, BLACK_PASS_ALPHA]);
}

/** Energia's hardcoded 0x410f90 main triangle layer. */
export class EnergiaMainTriangleEffect {
  constructor(mgl) { this.mgl = mgl; }

  render(seconds, { clear = false } = {}) {
    const { mgl } = this;
    if (clear) mgl.clear();
    const aspectBound = mgl.gl.drawingBufferHeight / mgl.gl.drawingBufferWidth * 0.5;
    const camera = energiaMainEffectCamera(seconds);
    const vertices = buildEnergiaMainEffectTriangles(seconds);

    mgl.matrixMode(mgl.PROJECTION);
    mgl.loadIdentity();
    mgl.frustum(-0.5, 0.5, -aspectBound, aspectBound, 1, 5000);
    mgl.matrixMode(mgl.MODELVIEW);
    mgl.loadMatrix(camera.viewMatrix);
    mgl.translate(...camera.translation);
    mgl.rotate(...camera.rotation);

    mgl.activeTexture(1);
    mgl.enableTexture(false);
    mgl.activeTexture(0);
    mgl.enableTexture(false);
    mgl.enableLighting(false);
    mgl.enableFog(false);
    mgl.enableCullFace(false);
    mgl.enableDepthTest(false);
    mgl.depthMask(false);
    mgl.enableBlend(true);
    mgl.blendFunc(mgl.SRC_ALPHA, mgl.ONE_MINUS_SRC_ALPHA);

    for (const color of energiaMainEffectPasses(seconds)) {
      mgl.color4(...color);
      mgl.begin(mgl.TRIANGLES);
      for (const vertex of vertices) mgl.vertex3(...vertex);
      mgl.end();
    }
    mgl.depthMask(true);
  }
}
