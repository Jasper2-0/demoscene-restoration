// stages.js — which half of the pipeline is a port and which is a recording.
//
// The restoration proceeds one stage at a time, and every stage spends a while
// with a working implementation on both sides: the original's recorded output,
// and the port that has to reproduce it. Being able to run a mixture is what
// makes a difference attributable — a wrong picture with computed animation
// over recorded emission says something a wrong picture with both computed does
// not.
//
// `web/README.md` used to describe that arrangement as though it existed. It
// did not; there was a table of prose and no mechanism. This is the mechanism,
// and the table is now generated from it.
//
// A STAGE WITH NO IMPLEMENTATION ON A SIDE SAYS SO. Asking for
// `?anim=computed` when there is no computed animation reports an error and
// keeps the recording; it does not quietly render the recording and let the
// page look like it honoured the request. That distinction is the whole reason
// to have this rather than a handful of booleans — a switch that silently
// ignores you is worse than no switch, because it makes a green check mean
// nothing.

