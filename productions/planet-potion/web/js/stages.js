const BY_NAME = new Map(PIPELINE.map((s) => [s.name, s]));

/**
 * Resolve `?stage=computed|recorded` overrides against what exists.
 *
 * Defaults to `computed` wherever there is a port and `recorded` otherwise, so
 * the page always shows the most finished thing it can without being asked.
 *
 * @returns {{choice: Object<string,string>, errors: string[]}}
 */
export function resolveStages(params) {
  const choice = {};
  const errors = [];
  for (const s of PIPELINE) {
    const want = params.get(s.name);
    if (want && want !== 'computed' && want !== 'recorded') {
      errors.push(`${s.name}=${want}: expected computed or recorded`);
    } else if (want && !s[want]) {
      const has = s.computed ? 'computed' : 'recorded';
      errors.push(`${s.name}=${want}: not implemented — only ${has} exists`);
    } else if (want) {
      choice[s.name] = want;
      continue;
    }
    choice[s.name] = s.computed ? 'computed' : 'recorded';
  }
  return { choice, errors };
}

/** The provenance map `window.__demo.state()` reports, one entry per stage. */
export function provenance(choice, extra = {}) {
  return Object.fromEntries(PIPELINE.map((s) => {
    const side = choice[s.name];
    return [s.name, {
      side,
      what: s.what,
      how: s[side] ?? 'not implemented',
      switchable: Boolean(s.computed && s.recorded),
      detail: extra[s.name],
    }];
  }));
}

/** A one-line summary for the status line: which stages are ports. */
export function summarise(choice) {
  const computed = PIPELINE.filter((s) => choice[s.name] === 'computed');
  return `${computed.length}/${PIPELINE.length} stages computed: ` +
    computed.map((s) => s.name).join(', ');
}
