import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const executablePath = path.join(repo, 'productions/energia/work', 'src', 'Energia_FIXED.exe');
const outputPath = path.join(
  repo, 'productions/energia/web', 'js', 'effects', 'mode4-marching-table.js',
);

// PE sections are file-aligned with their RVAs in this release. The native
// table at VA 0x43a5e0 is therefore at file offset 0x3a5e0. It contains 256
// rows of 16 signed 32-bit edge indices.
const TABLE_OFFSET = 0x3a5e0;
const CASE_COUNT = 256;
const ENTRIES_PER_CASE = 16;
const EXPECTED_PACKED_SHA256 = '19bf7699e214903d72c94c296546f2e31337d637a1e4b118c3108a0f428e809b';

const executable = fs.readFileSync(executablePath);
const rows = [];
const packed = Buffer.alloc(CASE_COUNT * ENTRIES_PER_CASE);
for (let caseIndex = 0; caseIndex < CASE_COUNT; caseIndex++) {
  const row = [];
  for (let entry = 0; entry < ENTRIES_PER_CASE; entry++) {
    const index = caseIndex * ENTRIES_PER_CASE + entry;
    const value = executable.readInt32LE(TABLE_OFFSET + index * 4);
    if (value < -1 || value > 11) {
      throw new Error(`invalid Energia triangle-table value ${value} at entry ${index}`);
    }
    row.push(value);
    packed.writeInt8(value, index);
  }
  rows.push(row);
}

const digest = crypto.createHash('sha256').update(packed).digest('hex');
if (digest !== EXPECTED_PACKED_SHA256) {
  throw new Error(`Energia triangle-table hash mismatch: ${digest}`);
}

const source = `// Generated by tools/extract-energia-mode4-table.mjs from
// Energia_FIXED.exe VA 0x43a5e0. Do not hand-edit this lookup table.

export const ENERGIA_MODE4_TRI_TABLE = Object.freeze([
${rows.map((row) => `  [${row.join(', ')}],`).join('\n')}
].map((row) => Object.freeze(row)));
`;

fs.writeFileSync(outputPath, source);
console.log(`wrote ${path.relative(repo, outputPath)} (${digest})`);
